import type { Night } from '../digest/types.js';

export function DigestPage({ night }: { night: Night }) {
  return (
    <>
      <h1>digest {night.night}</h1>
      {night.rows.length === 0 ? (
        <p class="mute">nothing ran</p>
      ) : (
        <table>
          <thead>
            <tr><th>job</th><th>owner</th><th>runs</th><th>retries</th><th>last status</th><th>last error</th><th>first</th><th>last</th></tr>
          </thead>
          <tbody>
            {night.rows.map((r) => (
              <tr>
                <td>{r.job}</td>
                <td>{r.owner ?? '—'}</td>
                <td>{r.runs}</td>
                <td class={r.retries >= 3 ? 'warn' : ''}>{r.retries}{r.retries >= 3 ? ' ⚠ retries' : ''}</td>
                <td class={r.lastStatus === 'fail' ? 'warn' : ''}>{r.lastStatus}{r.lastStatus === 'fail' ? ' ✕ fail' : ''}</td>
                <td>{r.lastError ?? '—'}</td>
                <td>{r.first}</td>
                <td>{r.last}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
      {night.badLines > 0 && <p class="mute">{night.badLines} unreadable line{night.badLines === 1 ? '' : 's'} skipped</p>}
    </>
  );
}
